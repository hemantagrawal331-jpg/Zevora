/**
 * Demo catalogue only. These are not live ZEVORA products.
 * Replace `images` on a record to publish a real photograph. Pages read the
 * image list, so the product screens do not need to change.
 */

const apparel = ["XS", "S", "M", "L", "XL"];
const bottoms = ["28", "30", "32", "34", "36"];

type Spec = {
  id: string;
  name: string;
  category: CategoryId;
  subcategory: string;
  priceInPaise: number;
  compareAtPriceInPaise?: number;
  colors?: ProductColor[];
  sizeLabels?: string[];
  stock?: number | Record<string, number>;
  images?: CatalogImage[];
  tags?: string[];
  material?: string;
  fit?: string;
  care?: string;
  isNewArrival?: boolean;
  isBestseller?: boolean;
  isActive?: boolean;
  popularity?: number;
  createdAt: string;
  description?: string;
};

function photo(src: string, alt: string, color: string, fit: "cover" | "contain" = "cover"): CatalogImage {
  return { src, alt, color, role: "main", fit };
}

function sizesFor(labels: string[], sku: string, stock: number | Record<string, number> = 4): ProductSize[] {
  return labels.map((label) => ({
    label,
    sku: `${sku}-${label.toLowerCase().replace(/\s+/g, "-")}`,
    stockQuantity: typeof stock === "number" ? stock : (stock[label] ?? 0),
  }));
}

function build(spec: Spec): Product {
  const category = getCategory(spec.category);
  const sizeLabels = spec.sizeLabels ?? apparel;
  const sku = `ZEV-${spec.id.toUpperCase()}`;
  const sizes = sizesFor(sizeLabels, sku, spec.stock ?? 4);
  const colors = spec.colors ?? [{ name: "Black", hex: "#171717" }];
  const label = subcategoryLabel(spec.category, spec.subcategory);
  return {
    id: spec.id,
    slug: spec.id,
    name: spec.name,
    description:
      spec.description ??
      `Demo listing for the ${spec.name}. The copy and price are sample data for the ZEVORA shop.`,
    category: spec.category,
    subcategory: spec.subcategory,
    priceInPaise: spec.priceInPaise,
    compareAtPriceInPaise: spec.compareAtPriceInPaise,
    images: spec.images ?? [
      {
        src: images.productFallback,
        alt: `Demo photograph pending for ${spec.name}`,
        role: "main",
        fit: "contain",
      },
    ],
    sizes,
    colors,
    sku,
    stockQuantity: sizes.reduce((total, size) => total + size.stockQuantity, 0),
    tags: [...new Set([category?.label ?? spec.category, label, ...(spec.tags ?? [])])],
    material: spec.material ?? "Sample fabric",
    fit: spec.fit ?? "Regular",
    care: spec.care ?? "Demo care note. Replace this with the real cloth instruction.",
    isNewArrival: spec.isNewArrival ?? false,
    isBestseller: spec.isBestseller ?? false,
    isActive: spec.isActive ?? true,
    popularity: spec.popularity ?? (spec.isBestseller ? 80 : 20),
    createdAt: spec.createdAt,
    demo: true,
  };
}

